-- A sitting of exposure practice: from the first rated video until the patient
-- pauses, finishes the sequence, or goes quiet. exposure_progress keeps one row
-- per QPV-II cycle (or review) that accumulates every rating across days; the
-- clinical team counts sessions per sitting (2 or 3 a week, up to 8).
--
-- A session belongs to the ratings of the same user and progress row whose
-- videoTimestamp falls between started_at and last_activity_at. One that was
-- never closed counts as ended two hours after its last activity; that is
-- decided when reading, not stored.

CREATE TABLE exposure_sessions (
  id               TEXT PRIMARY KEY,                -- generated by the client
  user_id          TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  qpvii_timestamp  INTEGER,                         -- the exposure_progress row it belongs to
  is_review        INTEGER NOT NULL DEFAULT 0,
  started_at       INTEGER NOT NULL,                -- first rating
  last_activity_at INTEGER NOT NULL,                -- latest rating
  ended_at         INTEGER,
  end_reason       TEXT CHECK (end_reason IN ('pause', 'completed'))
);
CREATE INDEX exposure_sessions_user ON exposure_sessions(user_id, started_at);

-- Rebuild the sessions of existing records from their ratings: a gap of more
-- than two hours between ratings starts a new session. They are stored as
-- ended with no reason, which marks them as reconstructed.
INSERT INTO exposure_sessions (id, user_id, qpvii_timestamp, is_review, started_at, last_activity_at, ended_at, end_reason)
WITH ratings AS (
  SELECT p.id AS progress_id, p.user_id, p.qpvii_timestamp, p.is_review,
         json_extract(r.value, '$.videoTimestamp') AS at
  FROM exposure_progress p, json_each(p.discomfort_ratings) r
),
gaps AS (
  SELECT *, CASE WHEN at - LAG(at) OVER (PARTITION BY progress_id ORDER BY at) <= 7200000 THEN 0 ELSE 1 END AS starts
  FROM ratings
),
numbered AS (
  SELECT *, SUM(starts) OVER (PARTITION BY progress_id ORDER BY at ROWS UNBOUNDED PRECEDING) AS n
  FROM gaps
)
SELECT 'r-' || progress_id || '-' || n, user_id, qpvii_timestamp, is_review, MIN(at), MAX(at), MAX(at), NULL
FROM numbered
GROUP BY progress_id, n;
